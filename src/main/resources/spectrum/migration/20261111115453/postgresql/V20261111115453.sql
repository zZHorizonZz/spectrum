CREATE TABLE "spectrum_store" ("id" varchar(26) COLLATE "C" NOT NULL, "name" varchar(64) NOT NULL, "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "deleted_at" timestamptz, CONSTRAINT "pk_spectrum_store" PRIMARY KEY ("id"));

COMMENT ON TABLE "spectrum_store" IS 'A store. Deleting a store sets `deleted_at` and keeps its rows.';

COMMENT ON COLUMN "spectrum_store"."id" IS 'The store ID, a ULID.';

COMMENT ON COLUMN "spectrum_store"."updated_at" IS 'The time of the last change of the store, which the database writes on each update.';

CREATE TABLE "spectrum_authorization_model" ("store" varchar(26) COLLATE "C" NOT NULL, "authorization_model_id" varchar(26) COLLATE "C" NOT NULL, "schema_version" varchar(5) NOT NULL, "serialized_protobuf" bytea NOT NULL, CONSTRAINT "pk_spectrum_authorization_model" PRIMARY KEY ("store", "authorization_model_id"));

COMMENT ON TABLE "spectrum_authorization_model" IS 'An authorization model of a store. Models never change after they are written, and the database refuses an update.';

COMMENT ON COLUMN "spectrum_authorization_model"."authorization_model_id" IS 'The model ID, a ULID. The latest model of a store has the greatest ID.';

COMMENT ON COLUMN "spectrum_authorization_model"."serialized_protobuf" IS 'The model, as a serialized `openfga.v1.AuthorizationModel`.';

CREATE TABLE "spectrum_tuple" ("id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, "store" varchar(26) COLLATE "C" NOT NULL, "object_type" varchar(128) COLLATE "C" NOT NULL, "object_id" varchar(255) COLLATE "C" NOT NULL, "relation" varchar(50) COLLATE "C" NOT NULL, "_user" varchar(256) COLLATE "C" NOT NULL, "user_type" varchar(7) NOT NULL, "condition_name" varchar(256), "condition_context" bytea, "inserted_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT "pk_spectrum_tuple" PRIMARY KEY ("id"));

CREATE UNIQUE INDEX "ux_spectrum_tuple_key" ON "spectrum_tuple" ("store", "object_type", "object_id", "relation", "_user");

CREATE INDEX "ix_spectrum_tuple_user_lookup" ON "spectrum_tuple" ("store", "_user", "relation", "object_type", "object_id");

COMMENT ON TABLE "spectrum_tuple" IS 'A relationship tuple of a store. The database records each write and delete of a tuple in the changelog, in the
transaction of the change, and refuses an update: a tuple changes by a delete and a write.';

COMMENT ON COLUMN "spectrum_tuple"."id" IS 'The tuple ID, which the database gives each tuple in the order it writes them. Read pages by ID.';

COMMENT ON COLUMN "spectrum_tuple"."_user" IS 'The user: an object such as `user:anne`, a typed wildcard such as `user:*`, or a userset such as
`group:eng#member`.';

COMMENT ON COLUMN "spectrum_tuple"."user_type" IS '`user` for an object, or `userset` for a typed wildcard or a userset.';

COMMENT ON COLUMN "spectrum_tuple"."condition_context" IS 'The condition context, as a serialized `google.protobuf.Struct`.';

CREATE TABLE "spectrum_changelog" ("id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, "store" varchar(26) COLLATE "C" NOT NULL, "object_type" varchar(256) COLLATE "C" NOT NULL, "object_id" varchar(256) NOT NULL, "relation" varchar(50) NOT NULL, "_user" varchar(512) NOT NULL, "condition_name" varchar(256), "condition_context" bytea, "operation" integer NOT NULL, "inserted_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT "pk_spectrum_changelog" PRIMARY KEY ("id"));

CREATE INDEX "ix_spectrum_changelog_store" ON "spectrum_changelog" ("store", "id");

COMMENT ON TABLE "spectrum_changelog" IS 'A write or a delete of a tuple of a store, which the triggers of the tuple table record in the transaction of the
change.';

COMMENT ON COLUMN "spectrum_changelog"."id" IS 'The change ID, which the database gives each change in the order it records them. Changes are in order of ID.';

COMMENT ON COLUMN "spectrum_changelog"."condition_context" IS 'The condition context, as a serialized `google.protobuf.Struct`.';

COMMENT ON COLUMN "spectrum_changelog"."operation" IS 'The `openfga.v1.TupleOperation` number: 0 for a write, 1 for a delete.';

CREATE TABLE "spectrum_assertion" ("store" varchar(26) COLLATE "C" NOT NULL, "authorization_model_id" varchar(26) COLLATE "C" NOT NULL, "assertions" bytea NOT NULL, CONSTRAINT "pk_spectrum_assertion" PRIMARY KEY ("store", "authorization_model_id"));

COMMENT ON TABLE "spectrum_assertion" IS 'The assertions of an authorization model.';

COMMENT ON COLUMN "spectrum_assertion"."assertions" IS 'The assertions, as a serialized `openfga.v1.Assertions` message.';

CREATE FUNCTION "rw_spectrum_store"() RETURNS trigger LANGUAGE plpgsql AS $leadseal$
BEGIN
  NEW."updated_at" := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$leadseal$;

CREATE TRIGGER "rw_spectrum_store" BEFORE UPDATE ON "spectrum_store" FOR EACH ROW EXECUTE FUNCTION "rw_spectrum_store"();

CREATE FUNCTION "tg_spectrum_authorization_model_update"() RETURNS trigger LANGUAGE plpgsql AS $leadseal$
BEGIN
  IF (NOT false) THEN
    RAISE EXCEPTION USING MESSAGE = 'An authorization model never changes.', ERRCODE = 'P0001';
  END IF;
  RETURN NULL;
END;
$leadseal$;

CREATE TRIGGER "tg_spectrum_authorization_model_update" AFTER UPDATE ON "spectrum_authorization_model" FOR EACH ROW EXECUTE FUNCTION "tg_spectrum_authorization_model_update"();

CREATE FUNCTION "tg_spectrum_tuple_insert"() RETURNS trigger LANGUAGE plpgsql AS $leadseal$
BEGIN
  INSERT INTO "spectrum_changelog" ("store", "object_type", "object_id", "relation", "_user", "condition_name", "condition_context", "operation") VALUES (NEW."store", NEW."object_type", NEW."object_id", NEW."relation", NEW."_user", NEW."condition_name", NEW."condition_context", 0);
  RETURN NULL;
END;
$leadseal$;

CREATE TRIGGER "tg_spectrum_tuple_insert" AFTER INSERT ON "spectrum_tuple" FOR EACH ROW EXECUTE FUNCTION "tg_spectrum_tuple_insert"();

CREATE FUNCTION "tg_spectrum_tuple_update"() RETURNS trigger LANGUAGE plpgsql AS $leadseal$
BEGIN
  IF (NOT false) THEN
    RAISE EXCEPTION USING MESSAGE = 'A tuple never changes: delete it and write it again.', ERRCODE = 'P0001';
  END IF;
  RETURN NULL;
END;
$leadseal$;

CREATE TRIGGER "tg_spectrum_tuple_update" AFTER UPDATE ON "spectrum_tuple" FOR EACH ROW EXECUTE FUNCTION "tg_spectrum_tuple_update"();

CREATE FUNCTION "tg_spectrum_tuple_delete"() RETURNS trigger LANGUAGE plpgsql AS $leadseal$
BEGIN
  INSERT INTO "spectrum_changelog" ("store", "object_type", "object_id", "relation", "_user", "operation") VALUES (OLD."store", OLD."object_type", OLD."object_id", OLD."relation", OLD."_user", 1);
  RETURN NULL;
END;
$leadseal$;

CREATE TRIGGER "tg_spectrum_tuple_delete" AFTER DELETE ON "spectrum_tuple" FOR EACH ROW EXECUTE FUNCTION "tg_spectrum_tuple_delete"();
